/**
 * 国税庁「類似業種比準価額計算上の業種目及び業種目別株価等について」
 *
 * ⚠️ 定期更新が必要なデータ
 * - 出典: https://www.nta.go.jp/law/tsutatsu/kobetsu/hyoka/
 * - 新年度分: 毎年7～8月頃公表（前年の確定値）
 * - 月次株価: 毎月公表（2ヵ月ごとの場合あり）
 * - 保存年数: 相続税申告期限（相続開始かり10ヶ月）を考慮し過去5年分を推奨
 *
 * 階層構造:
 * - 大分類のみ: mediumCategory = "（全体）", minorCategory = "（全体）"
 * - 中分類まで: minorCategory = "（全体）"
 * - 3階層すべて: 各フィールドに実際の名称
 *
 * フィールド説明:
 * - A: 前年の年平均株価（通達182条で使用する「前年の株価」）
 * - B_prime: 1株当たり年配当金額（類似業種の標本会社平均）
 * - C_prime: 1株当たり年利益金額
 * - D_prime: 1株当たり純資産価額
 * - monthlyA: 当年の月次株価（「直前3か月」計算に使用）
 */

export interface SimilarIndustryDataRow {
  majorCategory: string
  mediumCategory: string
  minorCategory: string
  no: number
  /** 前年の年平均株価（通達182条①） */
  A: number
  /** 1株当たり年配当金額 */
  B_prime: number
  /** 1株当たり年利益金額 */
  C_prime: number
  /** 1株当たり純資産価額 */
  D_prime: number
  /** 当年の月次株価 { "1月": xxx, "2月": xxx, ... } */
  monthlyA?: Record<string, number>
  /** 評価年（保存時に動的付加される） */
  year?: string
}

export interface SimilarIndustryDatabase {
  [year: string]: SimilarIndustryDataRow[]
}

